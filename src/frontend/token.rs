use crate::diagnostics::Location;

#[derive(Debug, Clone, PartialEq)]
pub enum TokenKind {
    Int(i64),
    Float(f64),
    Str(String),
    Char(char),
    RawText(String),
    Ident(String),

    Let,
    Const,
    Dec,
    Func,
    If,
    Elf,
    Els,
    Then,
    End,
    For,
    While,
    Do,
    To,
    In,
    From,
    Return,
    Break,
    Continue,
    Halt,
    True,
    False,
    And,
    Or,
    Not,
    Has,
    As,
    Import,
    Union,
    Intersection,
    Difference,
    SymmetricDifference,

    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Concat,
    Assign,
    Eq,
    NotEq,
    Lt,
    Gt,
    Le,
    Ge,
    PrintOp,
    ReadOp,
    Bang,
    At,
    ColonColon,
    Arrow,
    Bridge,
    RawBlockOpen,
    RawBlockClose,

    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Comma,
    Dot,
    Semi,
}

impl TokenKind {
    pub fn keyword_spelling(&self) -> Option<&'static str> {
        Some(match self {
            TokenKind::Let => "let",
            TokenKind::Const => "const",
            TokenKind::Dec => "dec",
            TokenKind::Func => "func",
            TokenKind::If => "if",
            TokenKind::Elf => "elf",
            TokenKind::Els => "els",
            TokenKind::Then => "then",
            TokenKind::End => "end",
            TokenKind::For => "for",
            TokenKind::While => "while",
            TokenKind::Do => "do",
            TokenKind::To => "to",
            TokenKind::In => "in",
            TokenKind::From => "from",
            TokenKind::Return => "return",
            TokenKind::Break => "break",
            TokenKind::Continue => "continue",
            TokenKind::Halt => "halt",
            TokenKind::True => "true",
            TokenKind::False => "false",
            TokenKind::And => "AND",
            TokenKind::Or => "OR",
            TokenKind::Not => "NOT",
            TokenKind::Has => "has",
            TokenKind::As => "as",
            TokenKind::Import => "import",
            TokenKind::Union => "UNION",
            TokenKind::Intersection => "INTERSECTION",
            TokenKind::Difference => "DIFFERENCE",
            TokenKind::SymmetricDifference => "SYMMETRIC_DIFFERENCE",
            _ => return None,
        })
    }

    pub fn describe(&self) -> String {
        match self {
            TokenKind::Int(_) => "integer literal".to_string(),
            TokenKind::Float(_) => "float literal".to_string(),
            TokenKind::Str(_) => "string literal".to_string(),
            TokenKind::Char(_) => "character literal".to_string(),
            TokenKind::RawText(_) => "raw block".to_string(),
            TokenKind::Ident(name) => format!("identifier `{name}`"),
            TokenKind::Let => "`let`".to_string(),
            TokenKind::Const => "`const`".to_string(),
            TokenKind::Dec => "`dec`".to_string(),
            TokenKind::Func => "`func`".to_string(),
            TokenKind::If => "`if`".to_string(),
            TokenKind::Elf => "`elf`".to_string(),
            TokenKind::Els => "`els`".to_string(),
            TokenKind::Then => "`then`".to_string(),
            TokenKind::End => "`end`".to_string(),
            TokenKind::For => "`for`".to_string(),
            TokenKind::While => "`while`".to_string(),
            TokenKind::Do => "`do`".to_string(),
            TokenKind::To => "`to`".to_string(),
            TokenKind::In => "`in`".to_string(),
            TokenKind::From => "`from`".to_string(),
            TokenKind::Return => "`return`".to_string(),
            TokenKind::Break => "`break`".to_string(),
            TokenKind::Continue => "`continue`".to_string(),
            TokenKind::Halt => "`halt`".to_string(),
            TokenKind::True => "`true`".to_string(),
            TokenKind::False => "`false`".to_string(),
            TokenKind::And => "`AND`".to_string(),
            TokenKind::Or => "`OR`".to_string(),
            TokenKind::Not => "`NOT`".to_string(),
            TokenKind::Has => "`has`".to_string(),
            TokenKind::As => "`as`".to_string(),
            TokenKind::Import => "`import`".to_string(),
            TokenKind::Union => "`UNION`".to_string(),
            TokenKind::Intersection => "`INTERSECTION`".to_string(),
            TokenKind::Difference => "`DIFFERENCE`".to_string(),
            TokenKind::SymmetricDifference => "`SYMMETRIC_DIFFERENCE`".to_string(),
            TokenKind::Plus => "`+`".to_string(),
            TokenKind::Minus => "`-`".to_string(),
            TokenKind::Star => "`*`".to_string(),
            TokenKind::Slash => "`/`".to_string(),
            TokenKind::Percent => "`%`".to_string(),
            TokenKind::Concat => "`++`".to_string(),
            TokenKind::Assign => "`=`".to_string(),
            TokenKind::Eq => "`==`".to_string(),
            TokenKind::NotEq => "`!=`".to_string(),
            TokenKind::Lt => "`<`".to_string(),
            TokenKind::Gt => "`>`".to_string(),
            TokenKind::Le => "`<=`".to_string(),
            TokenKind::Ge => "`>=`".to_string(),
            TokenKind::PrintOp => "`>!`".to_string(),
            TokenKind::ReadOp => "`>?`".to_string(),
            TokenKind::Bang => "`!`".to_string(),
            TokenKind::At => "`@`".to_string(),
            TokenKind::ColonColon => "`::`".to_string(),
            TokenKind::Arrow => "`->`".to_string(),
            TokenKind::Bridge => "`<->`".to_string(),
            TokenKind::RawBlockOpen => "`<<<`".to_string(),
            TokenKind::RawBlockClose => "`>>>`".to_string(),
            TokenKind::LParen => "`(`".to_string(),
            TokenKind::RParen => "`)`".to_string(),
            TokenKind::LBrace => "`{`".to_string(),
            TokenKind::RBrace => "`}`".to_string(),
            TokenKind::LBracket => "`[`".to_string(),
            TokenKind::RBracket => "`]`".to_string(),
            TokenKind::Comma => "`,`".to_string(),
            TokenKind::Dot => "`.`".to_string(),
            TokenKind::Semi => "`;`".to_string(),
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub location: Location,
}
